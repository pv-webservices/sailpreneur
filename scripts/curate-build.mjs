// Publish only the image variants the site references. public/images holds every variant the
// optimiser produced; anything no page, stylesheet, script or manifest points at is removed from dist/.
import { readdir, readFile, unlink, writeFile } from 'node:fs/promises';
import { resolve, join, relative } from 'node:path';

const root = resolve('dist');

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(entries.map((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)])));
  return files.flat();
}

const files = await walk(root);
const referenced = new Set();
for (const file of files.filter((f) => /\.(html|css|js|webmanifest|xml)$/.test(f))) {
  for (const match of (await readFile(file, 'utf8')).matchAll(/\/images\/[\w/.-]+\.(?:webp|avif|jpg|png)/g)) referenced.add(match[0]);
}
const images = files.filter((f) => relative(root, f).replaceAll('\\', '/').startsWith('images/'));
let removed = 0;
for (const file of images) {
  if (!referenced.has('/' + relative(root, file).replaceAll('\\', '/'))) { await unlink(file); removed += 1; }
}
console.log(`curate-build: ${referenced.size} image files published, ${removed} unreferenced removed from dist`);

// Every page is also reachable as /<page>/index.html: send those to the clean, trailing-slash URL.
const pages = files.map((f) => relative(root, f).replaceAll('\\', '/')).filter((f) => f.endsWith('index.html'));
const rules = pages.map((f) => `/${f} /${f.replace(/index\.html$/, '')} 301!`);
await writeFile(join(root, '_redirects'), `# Generated by scripts/curate-build.mjs\n${rules.join('\n')}\n`);
console.log(`curate-build: ${rules.length} index.html redirects written to dist/_redirects`);
